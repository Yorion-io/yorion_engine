import com.vanniktech.maven.publish.SonatypeHost

plugins {
    id("com.android.library")
    id("org.jetbrains.kotlin.android")
    id("com.vanniktech.maven.publish")
}

android {
    namespace = "io.yorion.engine"
    compileSdk = 35

    defaultConfig {
        minSdk = 21
        consumerProguardFiles("consumer-rules.pro")
    }

    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_1_8
        targetCompatibility = JavaVersion.VERSION_1_8
    }

    // Both directories are filled by scripts/build-android.sh and are not committed:
    //   src/main/jniLibs  ← libyorion_engine.so per ABI (cargo-ndk)
    //   src/main/kotlin   ← Kotlin API generated by UniFFI from engine/src/uniffi.udl
    sourceSets["main"].kotlin.srcDir("src/main/kotlin")
}

kotlin {
    // Match compileOptions above; works with whichever JDK (17+) runs Gradle.
    compilerOptions {
        jvmTarget.set(org.jetbrains.kotlin.gradle.dsl.JvmTarget.JVM_1_8)
    }
}

dependencies {
    // UniFFI's generated Kotlin calls into the Rust library through JNA.
    implementation("net.java.dev.jna:jna:5.15.0@aar")
}

mavenPublishing {
    publishToMavenCentral(SonatypeHost.CENTRAL_PORTAL, automaticRelease = true)
    // Signing is required by Maven Central; skip it for local builds without keys.
    if (!(findProperty("signingInMemoryKey") as String?).isNullOrBlank()) {
        signAllPublications()
    }
    coordinates(
        project.property("GROUP") as String,
        project.property("POM_ARTIFACT_ID") as String,
        project.property("VERSION_NAME") as String,
    )
}
